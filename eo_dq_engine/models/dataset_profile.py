"""
Enterprise Observability
Dataset Profile
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(slots=True)
class DatasetProfile:
    """
    Dataset classification generated by the Dataset Profiler.

    This model is intentionally independent of any specific
    observability product. It represents the characteristics
    of an incoming dataset that are used for rule selection.
    """

    #
    # Dataset identity
    #
    source: str
    dataset: str

    #
    # Classification
    #
    signal: str
    platform: str
    product: str
    schema: str

    #
    # Rule selection
    #
    rule_scope: str

    #
    # Detection metadata
    #
    confidence: int = 100
    detection_type: str = "pattern"

    #
    # Additional metadata
    #
    attributes: dict[str, str] = field(default_factory=dict)